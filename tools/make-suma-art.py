#!/usr/bin/env python3
"""Draws the SuMa decorator's window buttons and writes src/suma/SumaButtons.h.

The buttons are the SuMa 1 GUI kit's metal window ones, as its Finder windows
had them: a small bead in a sunken socket, dark grey, with a hint of the
version's accent at its bottom, and filled with the accent when pressed. Close,
minimize and zoom look alike. They are drawn here from scratch after measuring
the kit's pictures; none of them are used.

    python3 tools/make-suma-art.py [--preview out.png]
"""

import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("leopard_art",
	os.path.join(HERE, "make-leopard-art.py"))
leopard = importlib.util.module_from_spec(spec)
spec.loader.exec_module(leopard)

# each version's accent: dark, as the plain bead's lower edge and the pressed
# one's rim, and its middle and light shades, as the pressed bead's body and shine
VERSIONS = {
	"Orange": ((0x81, 0x41, 0x17), (0xd3, 0x6e, 0x00), (0xd3, 0xac, 0x84)),
	"Blue": ((0x0e, 0x59, 0x82), (0x2b, 0x92, 0xdb), (0x9f, 0xb5, 0xe2)),
	"Green": ((0x52, 0x57, 0x00), (0x80, 0x93, 0x00), (0xa5, 0xbc, 0x74)),
}
GREYS = ((0x2e, 0x2e, 0x2e), (0x53, 0x53, 0x53), (0x94, 0x94, 0x94))
INACTIVE_GREYS = ((0x60, 0x60, 0x60), (0x80, 0x80, 0x80), (0xb4, 0xb4, 0xb4))


def socket(size, body, accent_edge):
	"""A bead in a sunken socket: the socket dark at its top and light at its
	bottom, the bead dark at its rim, lit across its top, and its lower edge
	tinted."""
	import math
	dark, middle, light = body
	pixels = []
	r_out = size / 2.0 - 0.5
	r_in = r_out - 1.6
	c = size / 2.0
	n = leopard.SAMPLES
	for y in range(size + 1):
		for x in range(size):
			acc = [0.0, 0.0, 0.0, 0.0]
			for sy in range(n):
				for sx in range(n):
					px = x + (sx + 0.5) / n - c
					py = y + (sy + 0.5) / n - c
					d = math.hypot(px, py)
					if d > r_out:
						continue
					if d > r_in:
						# the socket: dark at its top, light at its bottom
						t = leopard.clamp((py / r_out + 1) / 2)
						col = leopard.mix((0x5a, 0x5a, 0x5a), (0xf1, 0xf1, 0xf1),
							t ** 1.5)
					else:
						ny = py / r_in
						col = leopard.mix(middle, dark, leopard.clamp((ny + 0.2)))
						if ny > 0.55 and accent_edge is not None:
							col = leopard.mix(col, accent_edge,
								leopard.clamp((ny - 0.55) / 0.45))
						# the shine across its top
						sx2, sy2 = px / (r_in * 0.7), (ny + 0.55) / 0.3
						s = math.hypot(sx2, sy2)
						if s < 1:
							col = leopard.mix(col, light, 0.9 * (1 - s * s))
						if d > r_in - 0.9:
							col = leopard.mix(col, dark, 0.6)
					acc[0] += col[0]
					acc[1] += col[1]
					acc[2] += col[2]
					acc[3] += 1
			if acc[3] == 0:
				pixels.append(0)
				continue
			alpha = acc[3] / (n * n)
			r, g, b = (int(round(v / acc[3])) for v in acc[:3])
			pixels.append((int(round(alpha * 255)) << 24) | (r << 16) | (g << 8) | b)
	return pixels


def main():
	root = os.path.dirname(HERE)
	target = os.path.join(root, "src", "suma", "SumaButtons.h")
	preview = None
	if "--preview" in sys.argv:
		preview = sys.argv[sys.argv.index("--preview") + 1]

	sizes = (("Large", 14), ("Small", 11))
	images = []
	with open(target, "w") as out:
		out.write("/*\n * Generated by tools/make-suma-art.py.\n"
			" * Distributed under the terms of the MIT License.\n */\n"
			"#ifndef SUMA_BUTTONS_H\n#define SUMA_BUTTONS_H\n\n"
			"// ARGB, row by row, each a button wide and a row taller, for the light\n"
			"// edge below it: the large ones for most windows, the small ones for\n"
			"// floating windows\n"
			"static const int32 kLargeButton = 14;\n"
			"static const int32 kSmallButton = 11;\n\n")
		for sizeName, size in sizes:
			for version, (dark, middle, light) in VERSIONS.items():
				plain = socket(size, GREYS, dark)
				pressed = socket(size, (dark, middle, light), None)
				for name in ("Close", "Minimize", "Zoom"):
					leopard.emit(out, "%s%s%s" % (version, name, sizeName),
						plain, size)
					leopard.emit(out, "%s%sPressed%s" % (version, name, sizeName),
						pressed, size)
				images.append((size, plain))
				images.append((size, pressed))
			pixels = socket(size, INACTIVE_GREYS, None)
			leopard.emit(out, "Inactive%s" % sizeName, pixels, size)
			images.append((size, pixels))
			out.write("\n")
		out.write("#endif\t// SUMA_BUTTONS_H\n")

	if preview:
		from PIL import Image
		scale = 6
		width = sum(s + 2 for s, _ in images) * scale
		img = Image.new("RGB", (width, 16 * scale), (0x50, 0x50, 0x50))
		x = 0
		for size, pixels in images:
			for py in range(size + 1):
				for px in range(size):
					p = pixels[py * size + px]
					a = (p >> 24) / 255.0
					c = tuple(int(((p >> s) & 0xff) * a + 0x50 * (1 - a))
						for s in (16, 8, 0))
					for yy in range(scale):
						for xx in range(scale):
							img.putpixel((x + px * scale + xx, py * scale + yy), c)
			x += (size + 2) * scale
		img.save(preview)


if __name__ == "__main__":
	main()
