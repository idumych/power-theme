# Generates ForwardingControlLook.{h,cpp} from Renku's ControlLook.h and
# HaikuControlLook.{h,cpp}. Usage:
#   python3 tools/gen-forwarding-look.py RENKU_TREE src/controllook-kit HELPER...
import re, sys
tree, out, wanted = sys.argv[1], sys.argv[2], sys.argv[3:]
pub = open(tree + '/headers/os/interface/ControlLook.h').read()
hh = open(tree + '/headers/private/interface/HaikuControlLook.h').read()
hc = open(tree + '/src/kits/interface/HaikuControlLook.cpp').read()

# the pure virtual declarations, with their original formatting
decls = []
for m in re.finditer(r'\tvirtual\s[^;]*?= 0;', pub, re.S):
    decls.append(m.group(0)[:-len(' = 0;')] + ';')

def strip_defaults(sig):
    return re.sub(r'\s*=\s*[^,)]+(?=,|\)|$)', '', sig)

def parse(decl):
    d = ' '.join(decl.replace('virtual', '').split()).rstrip(';')
    const = d.endswith(' const')
    if const: d = d[:-6]
    m = re.match(r'(.*?)\b(\w+)\((.*)\)$', d)
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    args = []
    for p in strip_defaults(params).split(','):
        p = p.strip()
        if p: args.append(re.search(r'(\w+)$', p).group(1))
    return ret, name, strip_defaults(params), args, const

# helper method definitions in HaikuControlLook.cpp, with closure
defs = {}
for m in re.finditer(r'\n\n([^\n]+)\nHaikuControlLook::(_\w+)\(', hc):
    start = m.start() + 2
    i = hc.index('{', m.end())
    depth = 0
    for j in range(i, len(hc)):
        if hc[j] == '{': depth += 1
        elif hc[j] == '}':
            depth -= 1
            if depth == 0: break
    defs.setdefault(m.group(2), []).append(hc[start:j + 1])
need, todo = set(), list(wanted)
while todo:
    n = todo.pop()
    if n in need: continue
    need.add(n)
    for body in defs[n]:
        todo += [c for c in re.findall(r'\b(_[A-Z]\w*)\(', body)
            if c in defs and c not in need]
prot = hh[hh.index('protected:'):hh.index('private:', hh.index('protected:'))]
hdecls = [d for d in re.findall(r'\t\t\t[^;]*?;', prot, re.S)
    if re.search(r'\b(_\w+)\(', d).group(1) in need]
helpers = [b for n in sorted(need) for b in defs[n]]
used_consts = [l for l in hc.split('\n') if l.startswith('static const')
    and any(re.search(r'\b' + l.split()[3] + r'\b', b) for b in helpers)]

H = open(out + '/ForwardingControlLook.h', 'w')
H.write('''/*
 * Copyright 2026, idumych.
 * Copyright 2009-2020 Haiku, Inc. (the helpers)
 * SPDX-License-Identifier: MIT
 *
 * The base of every Power Theme control look. Built from source for one
 * system, it is libbe's private HaikuControlLook, as before. Built once for
 * Renku (PT_PREBUILT_LOOK), it is a public BControlLook that hands every call
 * it doesn't override to libbe's default look, made with
 * create_default_control_look(this): the default look then calls back into
 * this look's overrides, so it draws the same as a subclass would, but never
 * depends on HaikuControlLook's private layout.
 *
 * Generated by tools/gen-forwarding-look.py from Renku's ControlLook.h and
 * HaikuControlLook; don't edit it by hand.
 */
#ifndef FORWARDING_CONTROL_LOOK_H
#define FORWARDING_CONTROL_LOOK_H


#ifndef PT_PREBUILT_LOOK

#include <HaikuControlLook.h>

namespace BPrivate {
typedef HaikuControlLook ForwardingControlLook;
}

#else

#include <ControlLook.h>

class BGradientLinear;


namespace BPrivate {


class ForwardingControlLook : public BControlLook {
public:
								ForwardingControlLook();
	virtual						~ForwardingControlLook();

''')
for d in decls: H.write(d + '\n')
H.write('\nprotected:\n')
for d in hdecls: H.write(d + '\n')
H.write('''
private:
			BControlLook*		fDefault;
};


}	// namespace BPrivate

#endif	// PT_PREBUILT_LOOK

#endif	// FORWARDING_CONTROL_LOOK_H
''')

C = open(out + '/ForwardingControlLook.cpp', 'w')
C.write('''/*
 * Copyright 2026, idumych.
 * Copyright 2009, Stephan Aßmus <superstippi@gmx.de>
 * Copyright 2012-2020 Haiku, Inc. (the helpers)
 * SPDX-License-Identifier: MIT
 *
 * Generated by tools/gen-forwarding-look.py; the helpers are copied from
 * Haiku's HaikuControlLook.cpp. Only compiled for a prebuilt look.
 */
#ifdef PT_PREBUILT_LOOK


#include "ForwardingControlLook.h"

#include <algorithm>

#include <Bitmap.h>
#include <GradientLinear.h>
#include <Region.h>
#include <Shape.h>
#include <View.h>


namespace BPrivate {


''')
C.write('\n'.join(used_consts) + '\n\n\n' if used_consts else '')
C.write('''ForwardingControlLook::ForwardingControlLook()
	:
	fDefault(create_default_control_look(this))
{
}


ForwardingControlLook::~ForwardingControlLook()
{
	delete fDefault;
}
''')
def wrap(head, items, tail):
    # Haiku style: break before 80 columns (tabs count 4), indent one tab
    lines, line = [], head
    for i, item in enumerate(items):
        piece = item + (', ' if i < len(items) - 1 else tail)
        if len((line + piece.rstrip()).expandtabs(4)) > 80 and line.strip():
            lines.append(line.rstrip())
            line = '\t' * (head.count('\t') + 1)
        line += piece
    if not items:
        line += tail
    return '\n'.join(lines + [line])

for d in decls:
    ret, name, params, args, const = parse(d)
    sig = wrap('ForwardingControlLook::%s(' % name,
        [p.strip() for p in params.split(',') if p.strip()],
        ')' + (' const' if const else ''))
    call = wrap('\t%sfDefault->%s(' % ('' if ret == 'void' else 'return ', name),
        args, ');')
    C.write('\n\n%s\n%s\n{\n%s\n}\n' % (ret, sig, call))
for b in helpers:
    C.write('\n\n' + b.replace('HaikuControlLook::', 'ForwardingControlLook::') + '\n')
C.write('''

}	// namespace BPrivate


#endif	// PT_PREBUILT_LOOK
''')
print(len(decls), 'forwards;', 'helpers:', sorted(need), 'consts:', used_consts)
