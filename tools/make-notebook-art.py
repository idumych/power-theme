#!/usr/bin/env python3
"""Turn the Notebook theme's pictures into C++ for its add-ons.

    python3 -I tools/make-notebook-art.py

Reads src/third_party/notebook/art (Hideaki Kamada's Notebook skin for
WindowBlinds, 1999) and writes src/third_party/notebook/decorator/
NotebookWindowArt.h and controllook/NotebookControlArt.h: each picture as
ARGB, row by row, with its size. The skin's magenta is transparent. Each of
its pictures holds a part's states side by side or one above the other, as
notebook.uis lays them out; they're cut apart here.
"""

import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = os.path.join(ROOT, "src", "third_party", "notebook")
ART = os.path.join(BASE, "art")

KEY = (255, 0, 255)


def load(name):
	return Image.open(os.path.join(ART, name + ".bmp")).convert("RGB")


def frames(image, count, across):
	"""The picture's count states, side by side or one above the other."""
	if across:
		width = image.width // count
		return [image.crop((i * width, 0, (i + 1) * width, image.height))
			for i in range(count)]
	height = image.height // count
	return [image.crop((0, i * height, image.width, (i + 1) * height))
		for i in range(count)]


def emit(out, ident, image):
	pixels = []
	for y in range(image.height):
		for x in range(image.width):
			pixel = image.getpixel((x, y))
			if pixel == KEY:
				pixels.append(0)
			else:
				r, g, b = pixel
				pixels.append(0xff000000 | (r << 16) | (g << 8) | b)
	out.write("static const uint32 %sPixels[] = {\n" % ident)
	for y in range(image.height):
		row = pixels[y * image.width:(y + 1) * image.width]
		out.write("\t" + ", ".join("0x%08x" % p for p in row) + ",\n")
	out.write("};\nstatic const Art %s = { %d, %d, %sPixels };\n\n"
		% (ident, image.width, image.height, ident))


def write(path, guard, items):
	with open(path, "w") as out:
		out.write("/*\n * Generated by tools/make-notebook-art.py from ../art,"
			" Hideaki Kamada's\n * Notebook skin for WindowBlinds (see"
			" ../README).\n */\n#ifndef %s\n#define %s\n\n" % (guard, guard))
		out.write("#include <SupportDefs.h>\n\n\n"
			"// a picture: its size, and its pixels as ARGB, row by row\n"
			"struct Art {\n\tint32\t\t\twidth;\n\tint32\t\t\theight;\n"
			"\tconst uint32*\tpixels;\n};\n\n\n")
		for ident, image in items:
			emit(out, ident, image)
		out.write("#endif\t// %s\n" % guard)


def main():
	window = []
	# the frame: active, then inactive
	for name, across in (("top", False), ("left", True), ("right", True),
			("bottom", False)):
		active, inactive = frames(load(name), 2, across)
		title = name.capitalize()
		window += [("k%sActive" % title, active),
			("k%sInactive" % title, inactive)]
	# the title bar's buttons: normal, pressed, and inactive (the fourth of
	# the six; WindowBlinds' TripleImages)
	for name in ("close", "min", "max"):
		states = frames(load(name), 6, True)
		title = name.capitalize()
		window += [("k%s" % title, states[0]),
			("k%sPressed" % title, states[1]),
			("k%sInactive" % title, states[3])]
	write(os.path.join(BASE, "decorator", "NotebookWindowArt.h"),
		"NOTEBOOK_WINDOW_ART_H", window)

	controls = []
	# buttons: normal, pressed, disabled, focused and default
	for i, state in enumerate(("", "Pressed", "Disabled", "Focused",
			"Default")):
		controls.append(("kButton%s" % state, frames(load("Button"), 5,
			True)[i]))
	# check boxes and radio buttons: off, on, and both disabled
	for name, ident in (("Checkbox", "kCheckBox"), ("radio", "kRadio")):
		for i, state in enumerate(("", "On", "Disabled", "OnDisabled")):
			controls.append(("%s%s" % (ident, state), frames(load(name), 4,
				True)[i]))
	write(os.path.join(BASE, "controllook", "NotebookControlArt.h"),
		"NOTEBOOK_CONTROL_ART_H", controls)


if __name__ == "__main__":
	main()
