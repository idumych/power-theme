#!/usr/bin/env python3
"""Write Expose Air Dark's pixel tables (ExposeAirArt.h) from its Aurorae window
decoration in src/third_party/expose/art/air. Needs librsvg's Python binding
(gi, Rsvg 2), pycairo and Pillow.

As KDE does, each sheet is drawn whole, and every named piece is cut out of it
by its element's rectangle. The frame's 10 pixels of shadow are left out:
app_server draws window shadows itself.

    python3 tools/make-expose-air-art.py
"""

import os

import cairo
import gi
gi.require_version("Rsvg", "2.0")
from gi.repository import Rsvg
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
EXPOSE = os.path.join(ROOT, "src", "third_party", "expose")
ART = os.path.join(EXPOSE, "art", "air")
OUTPUT = os.path.join(EXPOSE, "style", "ExposeAirArt.h")

PADDING = 10	# the Padding* of exposeairdarkrc: the decoration's shadow
MARGIN = 20		# room for pieces placed at negative coordinates

HEADER = """/*
 * Generated by tools/make-expose-air-art.py from Expose Air Dark, a KDE Plasma
 * window decoration by Mark Whittaker (store.kde.org/p/2357318).
 * Distributed under the terms of the GNU GPL, version 3 or later.
 */
#ifndef EXPOSE_AIR_ART_H
#define EXPOSE_AIR_ART_H


#include <SupportDefs.h>


// B_RGBA32 pixels, 0xAARRGGBB, not premultiplied
struct AirPicture {
	int32			width;
	int32			height;
	const uint32*	pixels;
};

"""


def render(name):
	handle = Rsvg.Handle.new_from_file(os.path.join(ART, name))
	ok, width, height = handle.get_intrinsic_size_in_pixels()
	surface = cairo.ImageSurface(cairo.FORMAT_ARGB32,
		int(width) + 2 * MARGIN, int(height + 0.5) + 2 * MARGIN)
	viewport = Rsvg.Rectangle()
	viewport.x, viewport.y = MARGIN, MARGIN
	viewport.width, viewport.height = width, height
	handle.render_document(cairo.Context(surface), viewport)
	surface.flush()
	sheet = Image.frombuffer("RGBa", (surface.get_width(),
		surface.get_height()), bytes(surface.get_data()), "raw", "BGRa",
		surface.get_stride(), 1).convert("RGBA")
	viewport.x, viewport.y = 0, 0
	return handle, viewport, sheet


def rect_of(handle, viewport, element):
	ok, ink, logical = handle.get_geometry_for_layer("#" + element, viewport)
	if not ok:
		raise SystemExit("no element " + element)
	return [round(logical.x) + MARGIN, round(logical.y) + MARGIN,
		round(logical.width), round(logical.height)]


def table(name, image):
	data = image.tobytes()
	words = ["0x%02x%02x%02x%02x" % (data[i + 3], data[i], data[i + 1],
		data[i + 2]) if data[i + 3] else "0" for i in range(0, len(data), 4)]
	lines = []
	for i in range(0, len(words), 8):
		lines.append("\t" + ", ".join(words[i:i + 8]) + ",")
	return ("static const uint32 k%sPixels[] = {\n%s\n};\n"
		"static const AirPicture k%s = { %d, %d, k%sPixels };\n\n"
		% (name, "\n".join(lines), name, image.width, image.height, name))


def main():
	out = [HEADER]

	handle, viewport, sheet = render("decoration.svg")
	for state, prefix in (("Active", "decoration-"),
			("Inactive", "decoration-inactive-")):
		for part in ("topleft", "top", "topright", "left", "right",
				"bottomleft", "bottom", "bottomright"):
			x, y, width, height = rect_of(handle, viewport, prefix + part)
			if part.endswith("left"):
				x += PADDING
				width -= PADDING
			if part.endswith("right"):
				width -= PADDING
			if part.startswith("top"):
				y += PADDING
				height -= PADDING
			if part.startswith("bottom"):
				height -= PADDING
			piece = sheet.crop((x, y, x + width, y + height))
			name = "Frame%s%s" % (state, part.title().replace("left", "Left")
				.replace("right", "Right"))
			out.append(table(name, piece))

	for button in ("close", "minimize", "maximize"):
		handle, viewport, sheet = render(button + ".svg")
		for state in ("active", "inactive", "pressed", "pressed-inactive",
				"hover", "hover-inactive"):
			x, y, width, height = rect_of(handle, viewport, state + "-center")
			name = "Button%s%s" % (button.title(),
				state.title().replace("-", ""))
			out.append(table(name, sheet.crop((x, y, x + width, y + height))))

	out.append("\n#endif\t// EXPOSE_AIR_ART_H\n")
	os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
	with open(OUTPUT, "w") as file:
		file.write("".join(out))
	print("wrote", os.path.relpath(OUTPUT, ROOT))


main()
