#!/usr/bin/env python3
"""Draws the Leopard decorator's window buttons and writes src/leopard/LeopardButtons.h.

The buttons are drawn here from scratch, in the style of Mac OS X 10.5's: a gel
bead with a dark rim, a shine across its top, a glow in its lower half and a light
edge below it, where the title bar catches the light. They are measured from
screenshots; nothing of Apple's artwork is used.

Each button is ARGB, row by row, to be mixed by the decorator with the title bar
behind it. A cell is a button wide and one row taller, for the light edge.

    python3 tools/make-leopard-art.py [--preview out.png]
"""

import math
import os
import sys

SAMPLES = 8

# the bead's colour under its shine and at its bottom, and its rim's: measured
# down the middle of each
COLOURS = {
	"Close": ((0xF6, 0x30, 0x31), (0xFD, 0xAE, 0xAE), (0x8A, 0x26, 0x29)),
	"Minimize": ((0xF4, 0xB0, 0x58), (0xFE, 0xE7, 0x75), (0xA8, 0x4E, 0x1F)),
	"Zoom": ((0x84, 0xC8, 0x52), (0xC9, 0xE9, 0x82), (0x30, 0x54, 0x20)),
	# Graphite's are all one colour
	"Graphite": ((0x8E, 0x9B, 0xB0), (0xD0, 0xD9, 0xE6), (0x4A, 0x53, 0x62)),
	# an inactive window's, and those of a button that can't be used
	"Inactive": ((0xC9, 0xC9, 0xC9), (0xEC, 0xEC, 0xEC), (0x8C, 0x8C, 0x8C)),
}


def mix(a, b, t):
	return tuple(x + (y - x) * t for x, y in zip(a, b))


def clamp(v, lo=0.0, hi=1.0):
	return max(lo, min(hi, v))


def bead(nx, ny, top, bottom, rim):
	"""The colour of the bead at (nx, ny), from -1 to 1 across it."""
	r = math.hypot(nx, ny)
	# lighter towards the bottom, where the light comes through it
	c = mix(top, bottom, clamp((ny + 0.3) / 1.05) ** 1.2)
	# darker round its edge
	c = mix(c, rim, 0.75 * clamp((r - 0.55) / 0.45) ** 2.2)
	# the shine: a small ellipse across the top, brightest in its middle
	sx, sy = nx / 0.5, (ny + 0.56) / 0.24
	s = math.hypot(sx, sy)
	if s < 1:
		c = mix(c, (255, 255, 255), 0.88 * (1 - s ** 2) ** 0.5)
	return c


def glyph(name, nx, ny, size):
	"""How much of a pressed button's glyph covers (nx, ny)."""
	w = 1.15 / (size / 2)  # the stroke's half width, in units of the radius
	if name == "Close":
		d = min(abs(nx - ny), abs(nx + ny)) / math.sqrt(2)
		return 1.0 if d < w and abs(nx) < 0.42 and abs(ny) < 0.42 else 0.0
	if name == "Minimize":
		return 1.0 if abs(ny) < w and abs(nx) < 0.5 else 0.0
	if name == "Zoom":
		bar = (abs(ny) < w and abs(nx) < 0.5) or (abs(nx) < w and abs(ny) < 0.5)
		return 1.0 if bar else 0.0
	return 0.0


def render(name, colours, size, pressed):
	top, bottom, rim = colours
	if pressed:
		top, bottom, rim = (tuple(c * 0.74 for c in x) for x in colours)
	base = top
	radius = size / 2.0
	rimWidth = 1.1 if size >= 12 else 0.9
	pixels = []
	for y in range(size + 1):
		for x in range(size):
			acc = [0.0, 0.0, 0.0, 0.0]
			for sy in range(SAMPLES):
				for sx in range(SAMPLES):
					px = x + (sx + 0.5) / SAMPLES
					py = y + (sy + 0.5) / SAMPLES
					dx, dy = px - radius, py - radius
					d = math.hypot(dx, dy)
					if d <= radius:
						if d > radius - rimWidth:
							# the rim, darkest at the top and lighter along the
							# bottom
							col = mix(rim, (0, 0, 0), 0.35 * clamp(-dy / radius))
							col = mix(col, bottom, 0.3 * clamp(dy / radius))
						else:
							inner = radius - rimWidth
							col = bead(dx / inner, dy / inner, top, bottom, rim)
							if pressed and glyph(name, dx / inner, dy / inner,
									size):
								col = mix(rim, (0, 0, 0), 0.25)
						a = 1.0
					else:
						# the light edge below, where the bar catches the light
						below = d - radius
						if below < 1.4 and dy > radius * 0.35:
							col = (255, 255, 255)
							a = 0.42 * (1 - below / 1.4) * clamp(dy / radius)
						else:
							continue
					acc[0] += col[0] * a
					acc[1] += col[1] * a
					acc[2] += col[2] * a
					acc[3] += a
			n = SAMPLES * SAMPLES
			alpha = acc[3] / n
			if alpha <= 0:
				pixels.append(0)
				continue
			r, g, b = (int(round(clamp(v / acc[3] / 255) * 255)) for v in acc[:3])
			a = int(round(alpha * 255))
			pixels.append((a << 24) | (r << 16) | (g << 8) | b)
	return pixels


def emit(out, label, pixels, size):
	out.write("static const uint32 k%s[%d] = {\n" % (label, len(pixels)))
	for y in range(size + 1):
		row = pixels[y * size:(y + 1) * size]
		out.write("\t" + ", ".join("0x%08x" % p for p in row) + ",\n")
	out.write("};\n")


def main():
	root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
	target = os.path.join(root, "src", "leopard", "LeopardButtons.h")
	preview = None
	if "--preview" in sys.argv:
		preview = sys.argv[sys.argv.index("--preview") + 1]

	sizes = (("Large", 14), ("Small", 11))
	images = []
	with open(target, "w") as out:
		out.write("/*\n * Generated by tools/make-leopard-art.py.\n"
			" * Distributed under the terms of the MIT License.\n */\n"
			"#ifndef LEOPARD_BUTTONS_H\n#define LEOPARD_BUTTONS_H\n\n"
			"// ARGB, row by row, each a button wide and a row taller, for the light\n"
			"// edge below it: the large ones for most windows, the small ones for\n"
			"// floating windows\n"
			"static const int32 kLargeButton = 14;\n"
			"static const int32 kSmallButton = 11;\n\n")
		for sizeName, size in sizes:
			for name, colours in COLOURS.items():
				for pressed in (False, True):
					if name == "Inactive" and pressed:
						continue
					glyphName = name
					label = "%s%s%s" % (name, "Pressed" if pressed else "", sizeName)
					if name == "Graphite" and pressed:
						# its glyphs depend on the button; drawn for each
						for which in ("Close", "Minimize", "Zoom"):
							pixels = render(which, colours, size, True)
							emit(out, "Graphite%sPressed%s" % (which, sizeName),
								pixels, size)
							images.append((size, pixels))
						continue
					pixels = render(glyphName, colours, size, pressed)
					emit(out, label, pixels, size)
					images.append((size, pixels))
			out.write("\n")
		out.write("#endif\t// LEOPARD_BUTTONS_H\n")

	if preview:
		from PIL import Image
		scale = 8
		width = sum(s + 2 for s, _ in images) * scale
		img = Image.new("RGB", (width, 16 * scale), (0xb4, 0xb4, 0xb4))
		x = 0
		for size, pixels in images:
			for py in range(size + 1):
				for px in range(size):
					p = pixels[py * size + px]
					a = (p >> 24) / 255.0
					bg = 0xb4 - (py * 2)
					c = tuple(int(((p >> s) & 0xff) * a + bg * (1 - a))
						for s in (16, 8, 0))
					for yy in range(scale):
						for xx in range(scale):
							img.putpixel((x + px * scale + xx, py * scale + yy), c)
			x += (size + 2) * scale
		img.save(preview)


if __name__ == "__main__":
	main()
