#!/usr/bin/env python3
"""Turn the AmigaOS 3 theme's pictures into C++ for its add-ons.

    python3 -I tools/make-amigaos3-art.py

Reads src/third_party/amigaos3/art (the public domain xfwm4 and GTK 2 Amiga3.x
themes) and writes src/third_party/amigaos3/decorator/AmigaOS3WindowArt.h and
controllook/AmigaOS3ControlArt.h: each picture as premultiplied-free ARGB,
row by row, with its size. The add-ons are built each from its own folder, so
each gets its own header.
"""

import os
import re

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = os.path.join(ROOT, "src", "third_party", "amigaos3")
ART = os.path.join(BASE, "art")

WINDOW = [
	"top-left", "top-right", "title-2", "title-3", "title-4", "close", "hide",
	"maximize", "left", "right", "bottom", "bottom-left", "bottom-right",
]

CONTROLS = [
	"button/button", "button/button-pressed", "button/button-ins",
	"c_box/c_box", "c_box/c_box-pressed", "radio/radio", "radio/radio-pressed",
	"entry/entry", "arrow/arrow-down-combo", "arrow/arrow-down-active-combo",
	"menubar/menubar", "menubar/menuitem", "progressbar/trough-h",
	"progressbar/progressbar-horiz", "scrollbar/trough-v",
	"scrollbar/trough-h", "scrollbar/trough-dots", "scrollbar/scrollbar_vertical",
	"scrollbar/scrollbar_horizontal", "scrollbar/thumb-v",
	"scrollbar/thumb-h", "scrollbar/arrow_up", "scrollbar/arrow_up_clicked",
	"scrollbar/arrow_down", "scrollbar/arrow_down_clicked",
	"scrollbar/arrow_left", "scrollbar/arrow_left_clicked",
	"scrollbar/arrow_right", "scrollbar/arrow_right_clicked",
	"scale/trough-horiz", "scale/trough-vert", "scale/slider-horiz",
	"scale/slider-vert", "scale/thumb-h", "scale/thumb-v",
	"notebook/notebook", "notebook/tab-top", "notebook/tab-top-active",
	"notebook/tab-bottom", "notebook/tab-bottom-active", "notebook/tab-left",
	"notebook/tab-left-active", "notebook/tab-right",
	"notebook/tab-right-active",
]


def identifier(name):
	parts = re.split(r"[-_/]", name)
	return "k" + "".join(p[:1].upper() + p[1:] for p in parts)


def emit(out, name, image):
	image = image.convert("RGBA")
	pixels = []
	for y in range(image.height):
		for x in range(image.width):
			r, g, b, a = image.getpixel((x, y))
			pixels.append((a << 24) | (r << 16) | (g << 8) | b)
	ident = identifier(name)
	out.write("static const uint32 %sPixels[] = {\n" % ident)
	for y in range(image.height):
		row = pixels[y * image.width:(y + 1) * image.width]
		out.write("\t" + ", ".join("0x%08x" % p for p in row) + ",\n")
	out.write("};\nstatic const Art %s = { %d, %d, %sPixels };\n\n"
		% (ident, image.width, image.height, ident))


def write(path, guard, comment, items):
	with open(path, "w") as out:
		out.write("/*\n * Generated by tools/make-amigaos3-art.py from %s.\n"
			" * The pictures are in the public domain (see ../README).\n */\n"
			"#ifndef %s\n#define %s\n\n" % (comment, guard, guard))
		out.write("#include <SupportDefs.h>\n\n\n"
			"// a picture: its size, and its pixels as ARGB, row by row\n"
			"struct Art {\n\tint32\t\t\twidth;\n\tint32\t\t\theight;\n"
			"\tconst uint32*\tpixels;\n};\n\n\n")
		for name, image in items:
			emit(out, name, image)
		out.write("#endif\t// %s\n" % guard)


def main():
	window = []
	for name in WINDOW:
		for state in ("active", "inactive"):
			window.append(("%s-%s" % (name, state), Image.open(os.path.join(ART,
				"xfwm4", "%s-%s.xpm" % (name, state)))))
		if name in ("close", "hide", "maximize"):
			window.append(("%s-pressed" % name, Image.open(os.path.join(ART,
				"xfwm4", "%s-pressed.xpm" % name))))
	# the resize grip, for the content's corner where the scroll bars meet
	window.append(("resizer", Image.open(os.path.join(ART, "gtk-2.0",
		"statusbar", "resizer.png"))))
	write(os.path.join(BASE, "decorator", "AmigaOS3WindowArt.h"),
		"AMIGAOS3_WINDOW_ART_H", "art/xfwm4", window)

	controls = [(name, Image.open(os.path.join(ART, "gtk-2.0", name + ".png")))
		for name in CONTROLS]
	write(os.path.join(BASE, "controllook", "AmigaOS3ControlArt.h"),
		"AMIGAOS3_CONTROL_ART_H", "art/gtk-2.0", controls)


if __name__ == "__main__":
	main()
